'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = { JOURNEY: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'journey-middle.js'), 'utf8'), context);
const [wall, tree, field] = [4, 5, 6].map(ch => context.JOURNEY[ch]);
const checkView = (unit, state) => {
  const view = unit.view(state, {});
  for (const key of ['scene','controls','caption','math','cpp','why','challenge']) assert.equal(typeof view[key], 'string');
  assert.match(view.scene, /<svg/);
  return view;
};

let climb = wall.initial({});
climb = wall.act(climb, 'hold', '0');
assert.equal(climb.route.length, 0);
for (const next of [17, 11, 17]) climb = wall.act(climb, 'hold', String(next));
assert.equal(climb.route.length, 3);
climb = wall.act(climb, 'compare');
assert.match(climb.note, /原第 3 步.*原第 1 步/);
climb = wall.act(climb, 'undo');
assert.equal(climb.route.length, 2);
assert.equal(climb.read, 0);
climb = wall.act(climb, 'compare');
assert.match(climb.note, /B3.*C2/);
assert.match(checkView(wall, climb).scene, /下一次回放/);

let song = tree.initial({personal:true,voices:[0,1,0]});
assert.match(tree.view(song).controls, /你的鼓点录制/);
assert.match(tree.view(song).controls, /data-audition="0,1,0"/);
const example = {personal:false,voices:[0,2,1]};
const updatedRecording = {personal:true,voices:[2,1,0,1]};
let working = tree.initial(example);
working = tree.act(working,'light');
assert.doesNotMatch(tree.view(working,example).controls,/data-op="recording"/);
assert.match(tree.view(working,updatedRecording).controls,/data-op="recording"/);
assert.equal(working.score,'咚嚓啪');
working = tree.act(working,'draft','',{score:'新作'},updatedRecording);
assert.equal(working.score,'咚嚓啪');
assert.equal(working.merges.length,1);
assert.match(tree.view(working,updatedRecording).controls,/value="新作"/);
working = tree.act(working,'score','',{score:'AAB'},updatedRecording);
assert.equal(working.score,'AAB');
assert.equal(working.source,'手写乐句');
const loaded = tree.act(working,'recording','',{score:'尚未采用'},updatedRecording);
assert.equal(loaded.score,'嚓啪咚啪');
assert.equal(loaded.draft,loaded.score);
assert.equal(loaded.merges.length,0);
assert.equal(loaded.sel.length,0);
assert.match(tree.view(loaded,updatedRecording).controls,/data-audition="2,1,0,1"/);
assert.equal(tree.act(working,'recording','',{},example).score,'AAB');
song = tree.act(song, 'score', '', {score:'AAAAAAAA B C D'});
const merge = (s, a, b) => tree.act(tree.act(tree.act(s,'select',a),'select',b),'merge');
let bad = merge(song,'l0','l1');
assert.match(tree.view(bad).cpp,/手选/);
assert.match(tree.view(bad).cpp,/takeRoot\("l0"\)/);
assert.doesNotMatch(tree.view(bad).cpp,/popMin/);
bad = merge(bad,'m0','l2');
bad = merge(bad,'m1','l3');
assert.match(tree.view(bad).math, /共 30 位；这组频数的最优值 16 位，等长编码 22 位/);
while (bad.merges.length) bad = tree.act(bad, 'unmerge');
for (let i=0;i<3;i++) bad=tree.act(bad,'light');
const complete = checkView(tree,bad);
assert.match(complete.cpp,/popMin/);
assert.match(complete.math, /共 16 位/);
const wordStream=complete.math.match(/：([01 ]+)。/)[1].split(' ');
const original=[...bad.score];
const words=new Map(original.map((v,i)=>[v,wordStream[i]]));
for(const [a,x] of words)for(const [b,y] of words) if(a!==b)assert(!y.startsWith(x));
assert.equal(wordStream.reduce((sum,x)=>sum+x.length,0),16);
let one=tree.act(song,'score','',{score:'呵呵呵'});
assert.match(tree.view(one).math,/0 0 0。共 3 位/);
const escaped=tree.act(song,'score','',{score:'<"&'});
assert(!tree.view(escaped).controls.includes('value="<"&'));
assert.match(tree.view(escaped).controls,/&lt;&quot;&amp;/);
assert.equal(tree.act(song,'score','',{score:'ABCDEF'}).score,song.score);

let court=field.initial({});
assert.match(checkView(field,court).math,/最少 3 次，共 2 种/);
for(let i=0;i<3;i++)court=field.act(court,'pass');
assert.equal(court.step,3);
assert.match(court.note,/已抵达/);
court=field.act(court,'variant');
assert.equal(court.step,0);
assert.match(field.view(court).math,/第 2 种/);
const edge=(s,a,b)=>field.act(field.act(s,'player',String(a)),'player',String(b));
court=edge(court,0,5);
assert.match(field.view(court).math,/最少 1 次，共 1 种/);
court=edge(court,0,5);court=edge(court,3,5);court=edge(court,4,5);
assert.match(field.view(court).math,/不可达/);
court=field.act(field.act(court,'mode','goal'),'player','0');
assert.match(field.view(court).math,/最少 0 次，共 1 种/);
console.log('PASS — route editing and paired readers; free Huffman merges, optimum, prefix codes and escaping; equal, direct, disconnected and zero-pass routes.');
