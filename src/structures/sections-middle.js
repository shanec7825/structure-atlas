  function forestDemo(raw){
    const relations=String(raw).trim().toUpperCase().split(/\s*;\s*/);
    const children=new Map(),parent=new Map(),order=new Set();
    for(const term of relations){
      const match=/^([A-Z]):([A-Z]*)$/.exec(term);
      if(!match||children.has(match[1]))return ["格式如 A:BC;B:D;R:S。每个父亲只写一次，孩子从左到右排列。"];
      const [,p,kids]=match;order.add(p);children.set(p,[...kids]);
      for(const k of kids){if(parent.has(k))return ["一个结点出现两次作为孩子，输入不是森林。"];parent.set(k,p);order.add(k);}
    }
    const roots=[...order].filter(v=>!parent.has(v)),left={},right={},steps=[],seen=new Set();
    function siblings(list){for(let i=1;i<list.length;i++){right[list[i-1]]=list[i];steps.push(list[i-1]+".right = "+list[i]+"，两者在同一组中相邻。");}}
    for(const [p,kids] of children){if(kids.length){left[p]=kids[0];steps.push(p+".left = "+kids[0]+"，进入第一个孩子。");siblings(kids);}}
    siblings(roots);
    const pre=[];
    function walk(v){if(!v||seen.has(v))return;seen.add(v);pre.push(v);walk(left[v]);walk(right[v]);}
    walk(roots[0]);
    if(seen.size!==order.size)return ["输入含环，无法从所有根还原整片森林。"];
    return ["森林根从左至右为 "+roots.join("、")+"。所有未设置的链接初始为空。",...steps,"从 "+roots[0]+" 做二叉先序，得到 "+pre.join(" → ")+"。"];
  }
