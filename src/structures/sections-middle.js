  function avlDeleteDemo(raw){
    const fields=String(raw).split("/");
    if(fields.length!==2)return ["输入格式为 插入序列 / 要删除的编号，如 30 20 40 10 25 / 40。"];
    const values=decimalKeys(fields[0]),deletion=decimalKeys(fields[1]);
    if(!values||!deletion||deletion.length!==1||values.length>12||new Set(values).size!==values.length)
      return ["请输入最多 12 个互异的 0–99 十进制整数，斜线后写一个待删键。每个逗号两侧都要有编号。"];
    const key=deletion[0];
    const h=n=>n?n.h:0,fix=n=>(n.h=1+Math.max(h(n.l),h(n.r)),n);
    let reporting=false;
    const steps=[];
    function rotate(n,right){
      const p=right?n.l:n.r;
      if(right){n.l=p.r;p.r=n;}else{n.r=p.l;p.l=n;}
      fix(n);fix(p);
      if(reporting)steps.push((right?"右旋 ":"左旋 ")+n.k+"。新子树根 "+p.k+"，旋后高度 "+p.h+"。");
      return p;
    }
    function balance(n){
      if(!n)return null;fix(n);
      const bf=h(n.l)-h(n.r);
      if(reporting)steps.push("回到 "+n.k+"：左高 "+h(n.l)+"，右高 "+h(n.r)+"，差 "+bf+"。");
      if(bf>1){if(h(n.l.l)<h(n.l.r))n.l=rotate(n.l,false);return rotate(n,true);}
      if(bf< -1){if(h(n.r.r)<h(n.r.l))n.r=rotate(n.r,true);return rotate(n,false);}
      return n;
    }
    function add(n,v){
      if(!n)return {k:v,l:null,r:null,h:1};
      if(v<n.k)n.l=add(n.l,v);else n.r=add(n.r,v);
      return balance(n);
    }
    function del(n,v){
      if(!n){steps.push("走到空链接，树里没有 "+v+"。");return null;}
      if(v<n.k)n.l=del(n.l,v);else if(v>n.k)n.r=del(n.r,v);
      else if(!n.l||!n.r){const keep=n.l||n.r;steps.push("摘下 "+v+"，原入口接 "+(keep?keep.k:"空")+"。");return keep;}
      else{let succ=n.r;while(succ.l)succ=succ.l;steps.push("用中序后继 "+succ.k+" 接替 "+v+" 的键，再删除旧后继。");n.k=succ.k;n.r=del(n.r,succ.k);}
      return balance(n);
    }
    const form=n=>n?n.k+(n.l||n.r?"("+form(n.l)+","+form(n.r)+")":""):"∅";
    let root=values.reduce(add,null);reporting=true;
    steps.push("初始 AVL "+form(root)+"。空树高 0，叶高 1。");
    root=del(root,key);steps.push("结果 "+form(root)+"。高度 "+h(root)+"。");return steps;
  }
